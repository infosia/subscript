//! The runtime symbol table the dev JIT binds by address.
//!
//! The ship tier resolves the same names from the runtime static library
//! at link time, so one list serves both tiers.

use cranelift_jit::JITBuilder;
use subscript_runtime::ffi;

macro_rules! runtime_symbols {
    ($($name:ident),+ $(,)?) => {
        &[$((stringify!($name), ffi::$name as *const u8)),+]
    };
}

